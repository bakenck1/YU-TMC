test("recognizes publication descriptions and retains furniture bundles", () => {
  for (const name of [
    "Казах.русс.толков.словарь терм. 30.04.07 в кол-ве 100шт",
    "Қазақ көтерілістер энциклопедия 27.03.15 в кол-ве 10шт",
    "Борискин В.П. Справочник технолога по добыче нефти",
    "География, методичка 1шт", "Методическое руководство по Зоологии",
    "Практикум по программированию", "Сыман К.Ж. Тағам гигиенасы. Оқу-әдістемелік құралы",
    "Еспенбетова Ш. Мұнай химиясы. Оқуәдістемелік құралы",
    "Әлем әдебиеті МҰҚАЖАНОВА", "Физика. Есептер жинағы",
    "Ленинджер Осн биохимии в 3-х том в кол-ве 30шт",
    "Кабиболла Сыдиыкулы 10 томдык", "Книга по электронике. 2-е изд.",
    "уч.лит-ра Морская техника", "самоучитель немец.языка",
    "В фонд библиотеки от авт. О.З. Зубаиров",
    "Набор книг о шкафах",
  ]) assert.equal(isOneCBook(name), true, name);
  for (const name of ["Комплект полок для книг", "Набор стеллажей для книг", "Комплект шкафов для книг"]) {
    assert.equal(isOneCBook(name), false, name);
  }
});
